window.RythuI18n = {
  currentLang: localStorage.getItem('rythu_lang') || 'en',

  init() {
    this.apply(this.currentLang);
  },

  setLanguage(lang) {
    if (lang !== 'en' && lang !== 'te') lang = 'en';
    this.currentLang = lang;
    localStorage.setItem('rythu_lang', lang);
    this.apply(lang);
  },

  toggle() {
    const nextLang = this.currentLang === 'en' ? 'te' : 'en';
    this.setLanguage(nextLang);
  },

  t(key) {
    const dict = window.RYTHU_TRANSLATIONS[this.currentLang] || window.RYTHU_TRANSLATIONS.en;
    return dict[key] || window.RYTHU_TRANSLATIONS.en[key] || key;
  },

  apply(lang) {
    document.documentElement.lang = lang;
    if (lang === 'te') {
      document.body.classList.add('te-active');
    } else {
      document.body.classList.remove('te-active');
    }

    // Update all elements with [data-i18n]
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = translation;
        } else {
          el.innerHTML = translation;
        }
      }
    });

    // Notify listeners or components
    window.dispatchEvent(new CustomEvent('rythu:lang-changed', { detail: { lang } }));
  }
};
